//! Bounded byte decoding shared by native and browser inference owners.
use super::*;

fn validate_lengths(
    mut lengths: impl ExactSizeIterator<Item = usize>,
    shape: &[usize],
    new_bytes: usize,
) -> Result<()> {
    if shape.len() != 3
        || !(1..=32).contains(&shape[0])
        || !(1..=512).contains(&shape[1])
        || !(1..=256).contains(&new_bytes)
        || lengths.len() != shape[0]
        || lengths.any(|len| len != shape[1])
    {
        return Err(
            "generation requires B exact T-byte prompts (B=1..32, T=1..512) and 1..256 new bytes"
                .into(),
        );
    }
    Ok(())
}

fn greedy(values: &[f32]) -> Result<u8> {
    if values.len() != 256 || values.iter().any(|v| !v.is_finite()) {
        return Err("generation requires 256 finite next-byte logits per row".into());
    }
    // Strict comparison selects the lowest byte ID on ties, including +/-0.
    let mut best = 0;
    for index in 1..values.len() {
        if values[index] > values[best] {
            best = index;
        }
    }
    Ok(best as u8)
}

/// Actual generated bytes, not an admission permit or a language-quality score.
/// Prompts are represented only by row hashes. Output may still contain private
/// or non-UTF-8 material; callers control storage, rendering and publication.
#[cfg(feature = "wgpu")]
#[derive(Serialize)]
pub struct ByteCorpusGeneration {
    schema: &'static str,
    artifact_id: String,
    revision: String,
    policy: ByteCorpusInferencePolicy,
    decoding: &'static str,
    window_shape: [usize; 2],
    prompt_sha256: Vec<String>,
    generated_bytes: Vec<Vec<u8>>,
    next_logits_f32le_sha256: Vec<String>,
    serving: Option<ServingIdentity>,
}

#[cfg(feature = "wgpu")]
#[derive(Serialize)]
struct ServingIdentity {
    generation: String,
    gate_sha256: String,
}

#[cfg(feature = "wgpu")]
impl ByteCorpusGeneration {
    pub fn artifact_id(&self) -> &str {
        &self.artifact_id
    }

    pub fn generated_bytes(&self) -> &[Vec<u8>] {
        &self.generated_bytes
    }

    pub fn to_json(&self) -> Result<String> {
        Ok(serde_json::to_string(self)?)
    }

    pub(super) fn bind_serving(&mut self, generation: u64, gate_sha256: &str) {
        self.serving = Some(ServingIdentity {
            generation: generation.to_string(),
            gate_sha256: gate_sha256.to_owned(),
        });
    }
}

#[cfg(feature = "wgpu")]
impl ResidentByteInference {
    /// Let language bindings reject borrowed prompt lengths before copying data.
    pub fn validate_generation(
        &self,
        prompt_lengths: impl ExactSizeIterator<Item = usize>,
        max_new_bytes: usize,
    ) -> Result<()> {
        validate_lengths(prompt_lengths, self.input_layout().shape(), max_new_bytes)
    }

    /// Recompute the full causal window for each next byte. No padding, EOS,
    /// UTF-8 conversion, sampling, KV cache or implicit prompt truncation.
    /// Positions and geometry reset to zero at every sliding window. The final
    /// target slot is synthetic and never used for loss or byte selection.
    pub async fn generate_greedy(
        &mut self,
        prompts: &[Vec<u8>],
        max_new_bytes: usize,
    ) -> Result<ByteCorpusGeneration> {
        self.validate_generation(prompts.iter().map(Vec::len), max_new_bytes)?;
        let shape = self.input_layout().shape();
        let [batch_size, steps] = [shape[0], shape[1]];
        let revision = self.attempted_revision();
        let mut windows = prompts.to_vec();
        let mut generated = vec![Vec::with_capacity(max_new_bytes); batch_size];
        let mut hashes = Vec::with_capacity(max_new_bytes);
        for _ in 0..max_new_bytes {
            let padded: Vec<_> = windows
                .iter()
                .map(|row| {
                    let mut row = row.clone();
                    row.push(0); // Only a target placeholder; never an input.
                    row
                })
                .collect();
            let rows: Vec<_> = padded.iter().map(Vec::as_slice).collect();
            let host = ByteLmBatch::from_windows(&rows)?;
            let batch = self.prepare_batch(&host)?;
            let tagged = self.forward(&batch)?;
            if tagged.artifact_id() != self.artifact_id()
                || tagged.forward().parameter_revision() != revision
            {
                return Err("generation lost artifact/revision ownership".into());
            }
            // Map B*256 next-byte logits, not B*T*256 full-window logits.
            let last = tagged.forward().prediction().select(1, steps - 1)?;
            let snapshot = last.snapshot()?;
            #[cfg(not(target_arch = "wasm32"))]
            let values = snapshot.read()?;
            #[cfg(target_arch = "wasm32")]
            let values = snapshot.read_async().await?;
            if values.len() != batch_size * 256 {
                return Err("generation next-byte logit shape changed".into());
            }
            let next = values
                .chunks_exact(256)
                .map(greedy)
                .collect::<Result<Vec<_>>>()?;
            let mut hash = Sha256::new();
            for value in &values {
                hash.update(value.to_le_bytes());
            }
            hashes.push(format!("{:x}", hash.finalize()));
            for ((window, output), byte) in windows.iter_mut().zip(&mut generated).zip(next) {
                output.push(byte);
                window.rotate_left(1);
                window[steps - 1] = byte;
            }
        }
        Ok(ByteCorpusGeneration {
            schema: "spiraltorch.byte_corpus.generation.v1",
            artifact_id: self.artifact_id().to_owned(),
            revision: revision.to_string(),
            policy: ByteCorpusInferencePolicy::FixedWindowFrozenV1,
            decoding: "greedy_lowest_id_sliding_window.v1",
            window_shape: [batch_size, steps],
            prompt_sha256: prompts
                .iter()
                .map(|p| format!("{:x}", Sha256::digest(p)))
                .collect(),
            generated_bytes: generated,
            next_logits_f32le_sha256: hashes,
            serving: None,
        })
    }
}

