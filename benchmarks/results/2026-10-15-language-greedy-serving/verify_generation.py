"""Replay private serving artifacts; publish only the explicitly selected result."""
import argparse
import hashlib
import json
from pathlib import Path
import struct


def check(condition, message):
    if not condition:
        raise ValueError(message)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def oracle(st, slot, prompts, count):
    windows = list(prompts)
    generated = [[] for _ in prompts]
    hashes = []
    steps = len(prompts[0])
    for _ in range(count):
        host = st.nn.ByteLmBatch.from_windows([p + b"\xff" for p in windows])
        forward = slot.forward(slot.prepare_batch(host))
        values = forward.prediction_tensor().snapshot().read_values()
        next_values = []
        for row in range(len(prompts)):
            scores = values[((row + 1) * steps - 1) * 256:(row + 1) * steps * 256]
            byte = max(range(256), key=scores.__getitem__)
            generated[row].append(byte)
            windows[row] = windows[row][1:] + bytes([byte])
            next_values.extend(scores)
        hashes.append(digest(struct.pack("<" + "f" * len(next_values), *next_values)))
    return generated, hashes


def run(input_path, count):
    import spiraltorch as st

    raw = Path(input_path).read_bytes()
    payload = json.loads(raw)
    gate = st.nn.ByteCorpusServingGate.from_json(payload["gate_json"])
    batch, steps = gate.batch_shape
    check(len(payload["windows"]) == batch * (steps + 1), "wrong private source windows")
    prompts = [bytes(payload["windows"][i * (steps + 1):i * (steps + 1) + steps])
               for i in range(batch)]
    def artifact(name):
        record = payload[name]
        return st.nn.ByteCorpusModelArtifact.from_json(record["json"], expected_id=record["id"])
    slot = gate.bootstrap_wgpu(artifact("incumbent"))
    adapter = slot.tensor_device().adapter_info()
    check(adapter["device_type"] != "Cpu", "CPU fallback is not this experiment")
    def verified(generation, expected_id):
        result = json.loads(slot.generate_greedy(prompts, max_new_bytes=count,
                                                expected_generation=generation))
        generated, hashes = oracle(st, slot, prompts, count)
        check(result["generated_bytes"] == generated, "generated bytes differ from oracle")
        check(result["next_logits_f32le_sha256"] == hashes, "next-logit hashes differ from oracle")
        check(result["artifact_id"] == slot.artifact_id == expected_id, "wrong selected artifact identity")
        check(slot.generation == generation, "wrong live generation")
        check(result["serving"] == dict(generation=str(generation), gate_sha256=gate.request_sha256),
              "wrong serving identity")
        check(result["prompt_sha256"] == [digest(p) for p in prompts], "wrong prompt identity")
        return result
    before = verified(0, payload["incumbent"]["id"])
    candidate = slot.prepare_candidate(artifact("candidate"))
    check(candidate.accepted, "candidate rejected by pinned policy")
    slot.activate(candidate)
    def stale():
        try:
            slot.generate_greedy(prompts, max_new_bytes=count, expected_generation=0)
        except ValueError as error:
            check("stale generation dispatch" in str(error), "unexpected rejection")
        else:
            raise ValueError("stale generation dispatch succeeded")
    stale()
    after = verified(1, payload["candidate"]["id"])
    slot.rollback(1)
    stale()
    restored = verified(2, payload["incumbent"]["id"])
    comparable = dict(restored, serving=dict(restored["serving"], generation="0"))
    check(comparable == before, "rollback changed output")
    return dict(schema="spiraltorch.byte_corpus.generation_native_qualification.v1",
                input_sha256=digest(raw), adapter=adapter, gate_sha256=gate.request_sha256,
                full_forward_oracle_exact=True, selected_artifact_ids_verified=True,
                stale_dispatch_rejected=True, rollback_exact=True,
                before=before, after=after, restored=restored,
                scope="Actual native WGPU greedy mechanics; no new updates or language-quality claim")


def main():
    if not __debug__:
        raise RuntimeError("qualification must not run under optimized Python")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--new-bytes", type=int, default=32)
    args = parser.parse_args()
    check(1 <= args.new_bytes <= 256, "new bytes must be in 1..256")
    check(args.input.resolve() != args.output.resolve(), "output must not replace private input")
    result = run(args.input, args.new_bytes)
    args.output.write_text(json.dumps(result, indent=2, allow_nan=False) + "\n")
    print(json.dumps({"output":str(args.output), "before_id":result["before"]["artifact_id"],
                      "after_id":result["after"]["artifact_id"], "oracle_exact":True, "rollback_exact":True}))


if __name__ == "__main__":
    main()
