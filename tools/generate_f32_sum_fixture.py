"""Generate exact f32 sum fixtures with Python integers (no Rust/Torch dependency)."""
import random


def units(bits):
    exponent = bits >> 23 & 255
    if exponent == 255:
        raise ValueError("input")
    magnitude = (bits & 0x7FFFFF) | (0x800000 if exponent else 0)
    return (-1 if bits >> 31 else 1) * (magnitude << max(0, exponent - 1))


def rounded(total):
    sign = 0x80000000 if total < 0 else 0
    magnitude = abs(total)
    shift = max(0, magnitude.bit_length() - 24)
    divisor = 1 << shift
    high, low = divmod(magnitude, divisor)
    if low * 2 > divisor or (low * 2 == divisor and high & 1):
        high += 1
    if high == 1 << 24:
        high >>= 1
        shift += 1
    if high < 1 << 23:
        return sign | high
    exponent = shift + 1
    return sign | (0x7F800000 if exponent >= 255 else (exponent << 23) | (high & 0x7FFFFF))


def expected(values):
    total, prefix = 0, 0
    for value in values:
        try:
            term = units(value)
        except ValueError:
            return "input"
        total += term
        prefix = rounded(units(prefix) + term)
        if prefix & 0x7F800000 == 0x7F800000:
            return "prefix"
    result = rounded(total)
    return "sum" if result & 0x7F800000 == 0x7F800000 else f"{result:08x}"


def cases():
    maximum, quarter, tail = 0x7F7FFFFF, 229 << 23, 204 << 23
    yield "zero", [0, 0x80000000]
    yield "minimum", [1]
    yield "normal_transition", [0x7FFFFF, 1]
    yield "even_tie", [0x3F800000, 103 << 23]
    yield "odd_tie", [0x3F800001, 103 << 23]
    yield "above_tie", [0x3F800000, 103 << 23, 1]
    yield "below_tie", [0x3F800000, 103 << 23, 0x80000001]
    yield "carry_exponent", [0x3FFFFFFF, 103 << 23]
    yield "finite_max", [maximum, quarter, quarter, tail | 0x80000000]
    yield "final_overflow", [maximum, quarter, quarter]
    yield "prefix_overflow", [maximum, maximum, maximum | 0x80000000]
    yield "nan", [0x7FC00000]
    yield "infinity", [0x7F800000]
    yield "exponent_span", [maximum, 1, maximum | 0x80000000]
    rng = random.Random(20261016)
    for index in range(32):
        # Ordinary and wide-range terms, with both signs and shuffled pairs.
        limit = 254 if index % 2 else 150
        values = [(rng.randrange(1, limit) << 23) | rng.getrandbits(23) |
                  (rng.getrandbits(1) << 31) for _ in range(5 + index)]
        if index % 3 == 0:
            values = [*values, *(v ^ 0x80000000 for v in values), rng.randrange(1, 0x7F7FFFFF)]
            rng.shuffle(values)
        yield f"random_{index}", values


def main():
    print("# Exact integer oracle, generated by tools/generate_f32_sum_fixture.py")
    print("# name expected_bits_or_guard input_bits...")
    for name, values in cases():
        for negative in (False, True):
            terms = [v ^ (0x80000000 if negative else 0) for v in values]
            print(name + ("_negative" if negative else ""), expected(terms), *(f"{v:08x}" for v in terms))


if __name__ == "__main__":
    main()
